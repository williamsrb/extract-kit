"""`extractkit context`: work out the stack and the build scope of a legacy checkout.

The kit never calls a model. This phase records what is deterministic: the
stack (from file markers) and the build scope (`buildscope.analyze`). The
judgment calls, which folders outside the build are not part of the product
(`context.exclude`) and which config keys carry endpoints (`context.live_config`),
are agent tasks that write into the same overlay, `<sidecar>/context/profile.yaml`.
`manifest.compose_overlays` layers it on top of the stack profile.
"""

from __future__ import annotations

import os
from argparse import Namespace
from collections.abc import Callable, Iterator
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import urlparse

from . import buildscope, guide, manifest, scope
from .common import dump_yaml, load_json, load_yaml, write_json, write_text
from .errors import ExtractkitError
from .outtree import (
    ensure_self_ignore,
    out_inside_source,
    resolve_out,
    resolve_source,
    write_self_ignore,
)

OVERLAY_REL = manifest.GENERATED_OVERLAY.as_posix()
BUILD_SCOPE_REL = "context/build-scope.json"
# Resources roots `steps/enonic/descriptors.py` `iter_resources_roots` scans.
ENONIC_MARKERS = ("application.xml", "site/site.xml")
OVERLAY_COMMENT = [
    "Generated by extractkit context and the context.exclude / context.live_config agent tasks.",
    "Composed on top of the stack profile. Sets only exclude and live_config.",
]


def stack_markers(source: Path, exclude: list[str] | tuple[str, ...] = ()) -> dict[str, str]:
    """Stack name to the marker file that names it, source-relative."""
    found: dict[str, str] = {}
    enonic = _enonic_marker(source, exclude)
    if enonic:
        found["enonic"] = enonic
    if (source / "composer.json").is_file():
        found["php"] = "composer.json"
    return found


def detect_stack(source: Path, exclude: list[str] | tuple[str, ...] = ()) -> str:
    """`enonic` or `php`, from file markers. Anything else is an error naming `--profile`."""
    found = stack_markers(source, exclude)
    if len(found) == 1:
        return next(iter(found))
    if found:
        raise ExtractkitError(
            f"{source} has markers for more than one stack: {', '.join(found)}",
            "pass --profile with the stack to extract",
            fix_args={"--profile": "enonic"},
        )
    raise ExtractkitError(
        f"no stack marker found under {source}",
        "looked for src/main/resources/application.xml or site/site.xml (enonic) and a "
        "root composer.json (php); pass --profile enonic (or php)",
        fix_args={"--profile": "enonic"},
    )


def _enonic_marker(source: Path, exclude: list[str] | tuple[str, ...]) -> str | None:
    for root, dirs, _files in os.walk(source):
        here = Path(root)
        dirs[:] = [
            d for d in dirs
            if d not in scope.SKIP_DIRS
            and not (here / d).is_symlink()
            and not scope.is_excluded((here / d).relative_to(source).as_posix(), exclude)
        ]
        if here.name == "resources" and here.parent.name == "main" and here.parent.parent.name == "src":
            for marker in ENONIC_MARKERS:
                if (here / marker).is_file():
                    return (here / marker).relative_to(source).as_posix()
    return None


def overlay_path(out: Path) -> Path:
    return out / manifest.GENERATED_OVERLAY


def cli_excludes(args: Namespace) -> list[str]:
    return scope.normalize(getattr(args, "exclude", None) or [])


def source_of(out: Path) -> Path | None:
    """The checkout a sidecar belongs to: its parent `.extract/` owner, else the MANIFEST."""
    derived = guide.sidecar_source(out)
    if derived:
        return derived
    path = out / "MANIFEST.yaml"
    if path.is_file():
        raw = (load_yaml(path, "MANIFEST.yaml").get("source") or {}).get("path")
        if raw:
            return Path(str(raw))
    return None


def _known_excludes(args: Namespace, out: Path) -> list[str]:
    """Excludes known before the stack is: flags, the overlay and the MANIFEST."""
    found: list = [*(getattr(args, "exclude", None) or [])]
    overlay = overlay_path(out)
    if overlay.is_file():
        found.extend(load_yaml(overlay, "context overlay").get("exclude") or [])
    manifest_path = out / "MANIFEST.yaml"
    if manifest_path.is_file():
        found.extend(load_yaml(manifest_path, "MANIFEST.yaml").get("exclude") or [])
    return scope.normalize(found)


def resolve_profile(args: Namespace, source: Path | None, out: Path) -> dict:
    """The composed profile: `--profile`, else MANIFEST `source.profile`, else detection."""
    from .profiles import validate_profile

    name = getattr(args, "profile", None)
    if not name:
        path = out / "MANIFEST.yaml"
        if path.is_file():
            name = (load_yaml(path, "MANIFEST.yaml").get("source") or {}).get("profile")
    if not name:
        if source is None:
            raise ExtractkitError(
                "no --profile, and MANIFEST.yaml has no source.profile",
                "pass --profile enonic (or php), or --source so the stack can be detected",
                fix_args={"--profile": "enonic"},
            )
        name = detect_stack(source, _known_excludes(args, out))
    return validate_profile(str(name), out, source if source is not None else source_of(out))


def write_overlay(
    out: Path,
    source: Path,
    stack: str,
    exclude: list[str],
    record: Callable[[str], None] | None = None,
) -> dict:
    """Write `context/build-scope.json` and `context/profile.yaml`; return the overlay.

    A re-run refreshes `extends` and the build scope and keeps `exclude` and
    `live_config`. `exclude` is `[]` only when the build scope carries no signal
    (no entry point, or nothing outside the build); otherwise the agent decides.
    """
    found = buildscope.analyze(source, exclude)
    scope_doc = {
        "branch": found.branch,
        "entry_points": found.entry_points,
        "in_scope": found.in_scope,
        "out_of_scope": found.out_of_scope,
    }
    existing = {}
    path = overlay_path(out)
    if path.is_file():
        existing = load_yaml(path, "context overlay")
    overlay: dict = {"_comment": OVERLAY_COMMENT, "extends": stack}
    if "exclude" in existing:
        overlay["exclude"] = existing["exclude"]
    elif not found.entry_points or not found.out_of_scope:
        overlay["exclude"] = []
    if "live_config" in existing:
        overlay["live_config"] = existing["live_config"]
    for rel, writer, payload in (
        (BUILD_SCOPE_REL, write_json, scope_doc),
        (OVERLAY_REL, lambda p, d: write_text(p, dump_yaml(d)), overlay),
    ):
        if record:
            record(f"write {out / rel}")
        writer(out / rel, payload)
    return overlay


def cmd_context(args: Namespace) -> int:
    source = resolve_source(getattr(args, "source", None))
    out = resolve_out(source, getattr(args, "out", None))
    if out_inside_source(source, out):
        ensure_self_ignore(source, lambda _text: None)
        write_self_ignore(source)
    profile = resolve_profile(args, source, out)
    stack = str(profile.get("name"))
    overlay = write_overlay(out, source, stack, cli_excludes(args))
    style = guide.style_for()
    found = load_json(out / BUILD_SCOPE_REL, BUILD_SCOPE_REL)
    lines = [
        f"extractkit context · {stack} · sidecar {guide.rel_to_cwd(out)}",
        f"  {style.glyph('done')} stack {stack}",
    ]
    if found["entry_points"]:
        lines.append(
            f"  {style.glyph('done')} build scope {found['branch']}: "
            f"{', '.join(found['entry_points'])}"
        )
        lines.append(f"      out of scope: {', '.join(found['out_of_scope']) or 'none'}")
    else:
        lines.append(f"  {style.glyph('skip')} build scope: no build entry point found")
    decided = "exclude" in overlay
    lines.append(
        f"  {style.glyph('done') if decided else style.glyph('pending')} exclude "
        + (f"{overlay['exclude']}" if decided else "undecided (agent task context.exclude)")
    )
    prog = getattr(args, "prog_display", None) or "extractkit"
    suggestion = guide.Suggestion(
        "Continue with the static inventory:",
        [prog, "run", "--source", str(source), "--out", str(out), "--until", "static"],
    )
    guide.emit(lines, guide.render_next(suggestion, style))
    return 0


