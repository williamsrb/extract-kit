MAX_TEXT_BYTES = 2_000_000


@dataclass
class _Claim:
    """One overlay fact and the text it must be found in."""

    where: str
    needle: str
    labels: tuple[str, ...] = ()
    found: bool = False


def _claims(overlay: dict) -> list[_Claim]:
    live = overlay.get("live_config") or {}
    claims: list[_Claim] = []

    def literal(where: str, needle: object) -> None:
        if needle:
            claims.append(_Claim(where, str(needle).casefold()))

    for name in ("site_url_keys", "hostmap_keys"):
        for key in live.get(name) or []:
            literal(f"live_config.{name} {key!r}", key)
    for key in (live.get("providers") or {}):
        literal(f"live_config.providers {key!r}", key)
    for index, rule in enumerate(live.get("env_endpoints") or []):
        at = f"live_config.env_endpoints[{index}]"
        literal(f"{at}.key {rule.get('key')!r}", rule.get("key"))
        literal(f"{at}.path {rule.get('path')!r}", rule.get("path"))
        origins = [*(rule.get("origins") or {}).values(), rule.get("default")]
        for origin in filter(None, origins):
            host = (urlparse(str(origin)).hostname or "").casefold()
            if host:
                claims.append(_Claim(f"{at} origin {origin!r}", host, tuple(host.split("."))))
        for url in rule.get("urls") or []:
            literal(f"{at}.urls {url!r}", url)
    return claims


def _source_texts(source: Path) -> Iterator[str]:
    """Lower-cased text of every readable source file, whatever `exclude` says."""
    for path in scope.iter_files(source):
        try:
            if path.stat().st_size > MAX_TEXT_BYTES:
                continue
            raw = path.read_bytes()
        except OSError:
            continue
        if b"\0" in raw[:4096]:
            continue
        yield raw.decode("utf-8", errors="replace").casefold()


def _harvested_text(out: Path) -> str:
    """Keys and values of the harvested Site Config and Config Env, as one lower-cased blob."""
    parts: list[str] = []
    runtime = out / "inventory" / "runtime.json"
    if runtime.is_file():
        doc = load_json(runtime, "inventory/runtime.json")
        for record in doc.get("siteConfig") or []:
            for key, value in (record.get("fields") or {}).items():
                parts.extend((str(key), str(value)))
        for item in doc.get("configEnv") or []:
            parts.extend((str(item.get("key") or ""), str(item.get("value") or "")))
    candidates = out / "inventory" / "live-config-candidates.json"
    if candidates.is_file():
        parts.extend(
            str(row.get("key"))
            for row in load_json(candidates, "inventory/live-config-candidates.json")
        )
    return "\n".join(parts).casefold()


def _resolve(claims: list[_Claim], text: str) -> None:
    for claim in claims:
        if not claim.found and claim.needle in text:
            claim.found = True
    for claim in claims:
        if claim.found or not claim.labels:
            continue
        # Template literals build a host from parts (`${...'test.' : ''}epayment.nets.eu`).
        claim.found = any(
            all(label in line for label in claim.labels) for line in text.splitlines()
        )


def grounding_gaps(out: Path) -> list[str]:
    """Overlay facts the source and the harvested config do not support.

    Checks `<sidecar>/context/profile.yaml` only; the operator override is exempt.
    """
    path = overlay_path(out)
    if not path.is_file():
        return []
    from steps.enonic import live_config

    from .profiles import validate_profile

    rel = OVERLAY_REL
    try:
        overlay = load_yaml(path, "context overlay")
        stack = str(overlay.get("extends") or "")
        if not stack:
            recorded = out / "MANIFEST.yaml"
            stack = str(((load_yaml(recorded, "MANIFEST.yaml") if recorded.is_file() else {})
                         .get("source") or {}).get("profile") or "")
        live_config.rules_from_profile(validate_profile(stack, out, None))
    except ExtractkitError as exc:
        return [f"{rel}: {exc}"]
    gaps: list[str] = []
    excluded = scope.normalize(overlay.get("exclude") or [])
    if excluded:
        scope_file = out / BUILD_SCOPE_REL
        outside = (
            set(load_json(scope_file, BUILD_SCOPE_REL).get("out_of_scope") or [])
            if scope_file.is_file() else set()
        )
        gaps.extend(
            f"{rel}: exclude {name!r} is not in {BUILD_SCOPE_REL} out_of_scope"
            for name in excluded if name not in outside
        )
    claims = _claims(overlay)
    if not claims:
        return gaps
    source = source_of(out)
    if source is None or not source.is_dir():
        return [*gaps, f"{rel}: cannot check live_config, the source checkout is not at {source}"]
    _resolve(claims, _harvested_text(out))
    for text in _source_texts(source):
        if all(claim.found for claim in claims):
            break
        _resolve(claims, text)
    gaps.extend(
        f"{rel}: {claim.where} is in neither the source nor the harvested live config"
        for claim in claims if not claim.found
    )
    return gaps
